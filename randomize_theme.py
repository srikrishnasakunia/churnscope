#!/usr/bin/env python3
"""
randomize_theme.py — generate a random but readable look for the app.

Picks a random colour hue and builds a matching palette (accent, background,
sidebar shade, text), a random Google Fonts pairing (body + headings), corner
roundness and base font size, then writes .streamlit/config.toml.

    python randomize_theme.py            # new random theme
    python randomize_theme.py --seed 7   # repeatable theme
    python randomize_theme.py --show     # print the theme without saving

The accent colour is checked against WCAG contrast (at least 4.5 : 1 against the
background) so buttons and links stay readable whatever hue comes up.
The charts in app.py read the accent colour from this file, so they follow too.
"""
import argparse
import colorsys
import random
from pathlib import Path

CONFIG = Path(__file__).resolve().parent / ".streamlit" / "config.toml"

# (body font, heading font) — all free on Google Fonts
FONT_PAIRS = [
    ("Inter", "Fraunces"),
    ("DM Sans", "DM Serif Display"),
    ("Nunito Sans", "Merriweather"),
    ("IBM Plex Sans", "IBM Plex Serif"),
    ("Work Sans", "Playfair Display"),
    ("Manrope", "Space Grotesk"),
    ("Source Sans 3", "Lora"),
    ("Outfit", "Outfit"),
    ("Lexend", "Bitter"),
    ("Karla", "Rubik"),
]
RADII = ["0.2rem", "0.4rem", "0.6rem", "0.9rem", "1.2rem"]
BASE_SIZES = [14, 15, 16]


def hsl_hex(h, s, l):
    r, g, b = colorsys.hls_to_rgb(h / 360, l, s)
    return "#{:02x}{:02x}{:02x}".format(round(r * 255), round(g * 255), round(b * 255))


def luminance(hex_color):
    def chan(c):
        c = int(c, 16) / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (chan(hex_color[i:i + 2]) for i in (1, 3, 5))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def google_font(name):
    return f"'{name}':https://fonts.googleapis.com/css2?family={name.replace(' ', '+')}:wght@400;600;700&display=swap"


def make_theme(rng: random.Random) -> dict:
    # Skip 45-85 deg (dark yellows turn muddy olive once darkened enough to read)
    # and 340-15 deg (too close to Streamlit's default red accent).
    # Draw uniformly over the allowed 285 degrees so every allowed hue is equally likely.
    u = rng.uniform(0, 285)
    hue = 15 + u if u < 30 else 85 + (u - 30)
    sat = rng.uniform(0.50, 0.78)
    background = hsl_hex(hue, rng.uniform(0.15, 0.35), rng.uniform(0.975, 0.99))
    lightness = rng.uniform(0.34, 0.44)
    primary = hsl_hex(hue, sat, lightness)
    while contrast(primary, background) < 4.5:  # darken until readable
        lightness -= 0.02
        primary = hsl_hex(hue, sat, lightness)
    body, heading = rng.choice(FONT_PAIRS)
    return {
        "hue": round(hue),
        "primaryColor": primary,
        "backgroundColor": background,
        "secondaryBackgroundColor": hsl_hex(hue, rng.uniform(0.25, 0.45), rng.uniform(0.92, 0.95)),
        "textColor": hsl_hex(hue, rng.uniform(0.15, 0.30), rng.uniform(0.11, 0.16)),
        "body": body,
        "heading": heading,
        "baseRadius": rng.choice(RADII),
        "baseFontSize": rng.choice(BASE_SIZES),
    }


def to_toml(t: dict) -> str:
    return f'''# Generated by randomize_theme.py (hue {t["hue"]}°, fonts: {t["body"]} / {t["heading"]})
[theme]
base = "light"
primaryColor = "{t["primaryColor"]}"
backgroundColor = "{t["backgroundColor"]}"
secondaryBackgroundColor = "{t["secondaryBackgroundColor"]}"
textColor = "{t["textColor"]}"
font = "{google_font(t["body"])}"
headingFont = "{google_font(t["heading"])}"
baseRadius = "{t["baseRadius"]}"
baseFontSize = {t["baseFontSize"]}
'''


def main():
    ap = argparse.ArgumentParser(description="Write a random Streamlit theme.")
    ap.add_argument("--seed", type=int, help="seed for a repeatable theme")
    ap.add_argument("--show", action="store_true", help="print only, don't save")
    args = ap.parse_args()

    theme = make_theme(random.Random(args.seed))
    toml = to_toml(theme)
    print(toml)
    print(f"accent contrast vs background: {contrast(theme['primaryColor'], theme['backgroundColor']):.1f} : 1")
    if not args.show:
        CONFIG.parent.mkdir(exist_ok=True)
        CONFIG.write_text(toml)
        print(f"saved -> {CONFIG}")


if __name__ == "__main__":
    main()
