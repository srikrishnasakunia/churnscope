"""ChurnScope — Streamlit front end for the Telco churn classifiers.

The app never retrains. It loads the five saved pipelines from model/,
scores whatever test CSV the user uploads, and reports metrics.

Look & feel: colours, fonts and corner radius come from .streamlit/config.toml
(generated by randomize_theme.py); the charts below derive their colours from
the same accent colour so the whole page matches.
"""
