import streamlit as st
from matplotlib.colors import LinearSegmentedColormap
from sklearn.metrics import (accuracy_score, classification_report, confusion_matrix,
                             f1_score, matthews_corrcoef, precision_score,
                             recall_score, roc_auc_score, roc_curve)

from churn_utils import ALL_FEATURES, MODEL_FILES, TARGET_COL, clean_frame, split_xy
from ui_effects import inject_motion_css, shader_banner

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"
SAMPLE_CSV = ROOT / "test_data.csv"

st.set_page_config(page_title="ChurnScope · Telco churn models", page_icon="📡", layout="wide")


# ---------- theme-aware chart styling ----------
def _opt(key, default):
    try:
        return st.get_option(key) or default
    except Exception:
        return default


ACCENT = _opt("theme.primaryColor", "#215da1")
TEXT = _opt("theme.textColor", "#1a222a")
PAPER = _opt("theme.backgroundColor", "#ffffff")


def _shift_hue(hex_color, degrees, lightness=None):
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    h = (h + degrees / 360) % 1
    l = l if lightness is None else lightness
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return "#{:02x}{:02x}{:02x}".format(round(r * 255), round(g * 255), round(b * 255))


# five well-separated colours built around the accent (one per model)
MODEL_COLOURS = dict(zip(MODEL_FILES, [ACCENT] + [_shift_hue(ACCENT, d, 0.45) for d in (72, 144, 216, 288)]))
HEAT = LinearSegmentedColormap.from_list("accent", [PAPER, _shift_hue(ACCENT, 0, 0.75), ACCENT])

plt.rcParams.update({
    "figure.facecolor": PAPER, "axes.facecolor": PAPER, "savefig.facecolor": PAPER,
    "text.color": TEXT, "axes.labelcolor": TEXT, "xtick.color": TEXT, "ytick.color": TEXT,
    "axes.edgecolor": "#c9ced4", "axes.spines.top": False, "axes.spines.right": False,
    "font.size": 9,
})


# ---------- loading & scoring ----------
@st.cache_resource
def load_models() -> dict:
    return {name: joblib.load(MODEL_DIR / fname) for name, fname in MODEL_FILES.items()}


def metrics_at(y, y_prob, cutoff) -> tuple[np.ndarray, dict]:
    """Turn probabilities into Yes/No at the chosen cut-off and score them."""
    y_pred = (y_prob > cutoff).astype(int)  # 0.5 reproduces model.predict()
    has_both = len(np.unique(y)) == 2
    return y_pred, {
        "Accuracy": accuracy_score(y, y_pred),
        "AUC": roc_auc_score(y, y_prob) if has_both else float("nan"),
        "Precision": precision_score(y, y_pred, zero_division=0),
        "Recall": recall_score(y, y_pred, zero_division=0),
        "F1": f1_score(y, y_pred, zero_division=0),
        "MCC": matthews_corrcoef(y, y_pred),
    }


def plot_confusion(y, y_pred, title):
    cm = confusion_matrix(y, y_pred, labels=[0, 1])
    fig, ax = plt.subplots(figsize=(4.2, 3.6))
    sns.heatmap(cm, annot=True, fmt="d", cmap=HEAT, cbar=False, ax=ax, linewidths=2, linecolor=PAPER,
                xticklabels=["Stays", "Churns"], yticklabels=["Stays", "Churns"],
                annot_kws={"size": 15, "weight": "bold"})
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    ax.set_title(title, fontsize=10)
    fig.tight_layout()
    return fig


def plot_cutoff_curve(y, y_prob, cutoff, colour):
    """Precision, recall and F1 across every cut-off, with the chosen one marked."""
    grid = np.linspace(0.05, 0.95, 91)
    prec, rec, f1 = [], [], []
    for t in grid:
        p = (y_prob > t).astype(int)
        if p.sum() < 10:  # too few flagged customers: precision is just noise, leave a gap
            prec.append(np.nan); rec.append(np.nan); f1.append(np.nan)
            continue
        prec.append(precision_score(y, p, zero_division=0))
        rec.append(recall_score(y, p, zero_division=0))
        f1.append(f1_score(y, p, zero_division=0))
    fig, ax = plt.subplots(figsize=(5.4, 3.6))
    ax.plot(grid, prec, color=colour, lw=2, label="Precision")
    ax.plot(grid, rec, color=_shift_hue(colour, 150, 0.45), lw=2, label="Recall")
    ax.plot(grid, f1, color="#8a8f96", lw=1.6, ls="--", label="F1")
    ax.axvline(cutoff, color=TEXT, lw=1, ls=":")
    ax.text(cutoff + 0.01, 0.04, f"cut-off {cutoff:.2f}", fontsize=8)
    ax.set_xlabel("Churn cut-off (probability above this = flagged)")
    ax.set_ylim(0, 1.02)
    ax.set_title("How the cut-off trades precision for recall", fontsize=10)
    ax.legend(fontsize=8, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.24), ncol=3)
    fig.tight_layout()
    return fig


def plot_roc(results, y):
    fig, ax = plt.subplots(figsize=(5.2, 4.2))
    for name, r in results.items():
        fpr, tpr, _ = roc_curve(y, r["y_prob"])
        ax.plot(fpr, tpr, lw=2, color=MODEL_COLOURS[name], label=f"{name} ({r['metrics']['AUC']:.3f})")
    ax.plot([0, 1], [0, 1], ls="--", c="#9aa0a6", lw=1)
    ax.set_xlabel("False positive rate")
    ax.set_ylabel("True positive rate")
    ax.set_title("ROC curves (cut-off independent)", fontsize=10)
    ax.legend(fontsize=7.5, loc="lower right", frameon=False)
    fig.tight_layout()
    return fig


def plot_bars(table):
    fig, ax = plt.subplots(figsize=(5.2, 4.2))
    shades = [ACCENT, _shift_hue(ACCENT, 0, 0.62), _shift_hue(ACCENT, 0, 0.80)]
    table[["Accuracy", "F1", "MCC"]].plot.barh(ax=ax, width=0.75, color=shades)
    ax.set_xlim(0, 1)
    ax.set_ylabel("")
    ax.set_title("Accuracy vs F1 vs MCC at the current cut-off", fontsize=10)
    ax.legend(fontsize=8, loc="lower right", frameon=False)
    fig.tight_layout()
    return fig


# ---------- sidebar ----------
st.sidebar.title("📡 ChurnScope")
st.sidebar.caption("Telco Customer Churn · M.Tech AIML · ML Assignment 2")

uploaded = st.sidebar.file_uploader("1. Upload test data (CSV)", type=["csv"])
if SAMPLE_CSV.exists():
    st.sidebar.download_button("Download sample test_data.csv", SAMPLE_CSV.read_bytes(),
                               file_name="test_data.csv", mime="text/csv")
use_sample = st.sidebar.checkbox("…or use the bundled test_data.csv", value=uploaded is None)

model_name = st.sidebar.selectbox("2. Choose a model", list(MODEL_FILES.keys()))

cutoff = st.sidebar.slider(
    "3. Churn cut-off", min_value=0.05, max_value=0.95, value=0.50, step=0.05,
    help="A customer is flagged as 'will churn' when the model's churn probability is above this value. "
         "0.50 is the models' default.")
if cutoff < 0.5:
    st.sidebar.caption("⬇ Lower cut-off: catches more churners, but more false alarms.")
elif cutoff > 0.5:
    st.sidebar.caption("⬆ Higher cut-off: fewer false alarms, but more churners slip through.")
else:
    st.sidebar.caption("Default cut-off — matches the README results table.")

# ---------- header ----------
inject_motion_css(ACCENT)
shader_banner(
    ACCENT,
    subtitle="Five classifiers trained offline on 80% of the IBM Telco data. "
             "Upload the held-out rows and the saved models score them live.",
    chip="Nothing is retrained here · move the cut-off slider to explore",
)
st.write(
    "Upload the held-out test rows (or any CSV with the same columns plus **Churn**) from the sidebar. "
    "Move the **cut-off slider** to see how each model trades caught churners against false alarms."
)

# ---------- data ----------
if uploaded is not None:
    raw = pd.read_csv(uploaded)
    source = uploaded.name
elif use_sample and SAMPLE_CSV.exists():
    raw = pd.read_csv(SAMPLE_CSV)
    source = "bundled test_data.csv"
else:
    st.info("Upload a CSV from the sidebar to begin.")
    st.stop()

try:
    df = clean_frame(raw)
    X, y = split_xy(df)
except ValueError as err:
    st.error(str(err))
    st.caption(f"Required columns: {', '.join(ALL_FEATURES)} and {TARGET_COL}")
    st.stop()

if y is None or y.isna().any():
    st.error(f"The CSV needs a '{TARGET_COL}' column with Yes/No (or 1/0) values to compute metrics.")
    st.stop()

c1, c2, c3, c4 = st.columns(4)
c1.metric("Rows scored", f"{len(df):,}")
c2.metric("Actual churners", f"{int(y.sum()):,}")
c3.metric("Churn rate", f"{y.mean():.1%}")
c4.metric("Cut-off in use", f"{cutoff:.2f}")
with st.expander(f"Preview of {source}"):
    st.dataframe(raw.head(20), width="stretch")

models = load_models()
results = {}
for name, pipe in models.items():
    prob = pipe.predict_proba(X)[:, 1]
    pred, mets = metrics_at(y, prob, cutoff)
    results[name] = {"y_prob": prob, "y_pred": pred, "metrics": mets}

# ---------- tabs ----------
tab_one, tab_all = st.tabs([f"🔍 {model_name}", "📊 Compare all five models"])

with tab_one:
    r = results[model_name]
    _, base = metrics_at(y, r["y_prob"], 0.5)
    cols = st.columns(6)
    for col, (k, v) in zip(cols, r["metrics"].items()):
        delta = None if abs(cutoff - 0.5) < 1e-9 or k == "AUC" else f"{v - base[k]:+.4f} vs 0.50"
        col.metric(k, f"{v:.4f}", delta=delta)

    left, right = st.columns([1, 1.25])
    with left:
        st.pyplot(plot_confusion(y, r["y_pred"], f"Confusion matrix — {model_name}"))
        tn, fp, fn, tp = confusion_matrix(y, r["y_pred"], labels=[0, 1]).ravel()
        st.caption(f"Caught **{tp} of {tp + fn}** churners; **{fp}** loyal customers were wrongly flagged.")
    with right:
        st.pyplot(plot_cutoff_curve(y, r["y_prob"], cutoff, MODEL_COLOURS[model_name]))

    st.markdown("**Classification report**")
    rep = classification_report(y, r["y_pred"], target_names=["Stays (0)", "Churns (1)"],
                                output_dict=True, zero_division=0)
    st.dataframe(pd.DataFrame(rep).T.round(3), width="stretch")

    out = raw.copy()
    out["Predicted_Churn"] = np.where(r["y_pred"] == 1, "Yes", "No")
    out["Churn_Probability"] = r["y_prob"].round(4)
    st.download_button("Download predictions as CSV", out.to_csv(index=False).encode(),
                       file_name=f"predictions_{MODEL_FILES[model_name].replace('.joblib', '')}"
                                 f"_cutoff{cutoff:.2f}.csv",
                       mime="text/csv")

with tab_all:
    table = pd.DataFrame({n: r["metrics"] for n, r in results.items()}).T
    table.index.name = "Model"
    highlight = _shift_hue(ACCENT, 0, 0.88)
    st.dataframe(table.style.format("{:.4f}").highlight_max(axis=0, color=highlight),
                 width="stretch")
    best = table["MCC"].idxmax()
    st.success(f"Best balanced performer at cut-off {cutoff:.2f} (highest MCC): **{best}**")

    a, b = st.columns(2)
    with a:
        st.pyplot(plot_roc(results, y))
    with b:
        st.pyplot(plot_bars(table))

st.caption("Positive class = customer churns. Models: scikit-learn pipelines saved with joblib. "
           "Theme generated by randomize_theme.py.")
